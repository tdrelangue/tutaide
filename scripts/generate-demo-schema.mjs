/**
 * Writes src/lib/demo/schema-sql.ts: the SQL that creates every table of
 * prisma/schema.prisma, run on the in-memory demo database at each demo start.
 *
 * Run after any change to prisma/schema.prisma:  npm run demo:schema
 */
import { execSync } from "child_process";
import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sql = execSync(
  "npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script",
  { cwd: root, encoding: "utf8" }
);

const out = join(root, "src", "lib", "demo", "schema-sql.ts");
writeFileSync(
  out,
  "// Generated by scripts/generate-demo-schema.mjs from prisma/schema.prisma. Do not edit.\n" +
    "// Regenerate with `npm run demo:schema` after any schema change.\n" +
    `export const DEMO_SCHEMA_SQL = ${JSON.stringify(sql)};\n`
);
console.log(`Demo schema written: ${out} (${sql.split("\n").length} lines of SQL)`);
